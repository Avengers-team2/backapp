def is_same_industry(store: dict, industry_code: str) -> bool:
    """상가정보 점포 한 건이 모델 업종 코드와 같은 업종인가"""
    rule = _MAP.get(industry_code)
    if not rule:
        return False
    if store.get("indsSclsCd") in rule.get("codes", ()):
        return True
    names = f"{store.get('indsSclsNm', '')} {store.get('indsMclsNm', '')}"
    return any(k in names for k in rule.get("keywords", ()))


def has_rule(industry_code: str) -> bool:
    return industry_code in _MAP
